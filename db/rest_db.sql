-- ============================================================
-- Orders table
-- Each row represents one food item within an order
-- ============================================================

CREATE TABLE orders (
    order_id INTEGER NOT NULL,
    item_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    total_price NUMERIC(10, 2) NOT NULL,

    CONSTRAINT orders_pkey
        PRIMARY KEY (order_id, item_id),

    CONSTRAINT orders_item_fk
        FOREIGN KEY (item_id)
        REFERENCES food_items (item_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT orders_quantity_positive
        CHECK (quantity > 0),

    CONSTRAINT orders_total_price_nonnegative
        CHECK (total_price >= 0)
);


-- ============================================================
-- Order tracking table
-- ============================================================

CREATE TABLE order_tracking (
    order_id INTEGER NOT NULL,

    status VARCHAR(50) NOT NULL
        DEFAULT 'pending',

    CONSTRAINT order_tracking_pkey
        PRIMARY KEY (order_id),

    CONSTRAINT order_tracking_status_check
        CHECK (
            status IN (
                'pending',
                'confirmed',
                'preparing',
                'ready',
                'out for delivery',
                'in transit',
                'delivered',
                'cancelled'
            )
        )
);


