-- ============================================================
-- Food items table
-- ============================================================

CREATE TABLE food_items (
    item_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,

    CONSTRAINT food_items_pkey
        PRIMARY KEY (item_id),

    CONSTRAINT food_items_name_unique
        UNIQUE (name),

    CONSTRAINT food_items_price_positive
        CHECK (price >= 0)
);


