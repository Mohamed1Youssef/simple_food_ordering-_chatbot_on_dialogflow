-- ============================================================
-- Function: get_price_for_item
--
-- Returns the price of a food item.
-- Returns -1 when the item does not exist.
--
-- The comparison is case-insensitive:
-- Pizza, pizza and PIZZA will all match.
-- ============================================================

CREATE OR REPLACE FUNCTION get_price_for_item(
    p_item_name VARCHAR
)
RETURNS NUMERIC(10, 2)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_price NUMERIC(10, 2);
BEGIN
    SELECT price
    INTO v_price
    FROM food_items
    WHERE LOWER(name) = LOWER(TRIM(p_item_name));

    IF NOT FOUND THEN
        RETURN -1;
    END IF;

    RETURN v_price;
END;
$$;


-- ============================================================
-- Function: get_total_order_price
--
-- Returns the total price of an order.
-- Returns -1 when the order does not exist.
-- ============================================================

CREATE OR REPLACE FUNCTION get_total_order_price(
    p_order_id INTEGER
)
RETURNS NUMERIC(10, 2)
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_total_price NUMERIC(10, 2);
BEGIN
    SELECT SUM(total_price)
    INTO v_total_price
    FROM orders
    WHERE order_id = p_order_id;

    IF v_total_price IS NULL THEN
        RETURN -1;
    END IF;

    RETURN v_total_price;
END;
$$;


-- ============================================================
-- Procedure: insert_order_item
--
-- Inserts an item into an order.
--
-- If the same item already exists in the order, its new
-- quantity is added to the existing quantity.
--
-- Example:
-- Existing order contains 2 pizzas.
-- User adds 1 pizza.
-- Final quantity becomes 3 pizzas.
-- ============================================================

CREATE OR REPLACE PROCEDURE insert_order_item(
    p_food_item VARCHAR,
    p_quantity INTEGER,
    p_order_id INTEGER
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item_id INTEGER;
    v_price NUMERIC(10, 2);
BEGIN
    -- Validate the order ID
    IF p_order_id IS NULL OR p_order_id <= 0 THEN
        RAISE EXCEPTION
            'Invalid order ID: %',
            p_order_id;
    END IF;

    -- Validate the quantity
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE EXCEPTION
            'Quantity must be greater than zero. Received: %',
            p_quantity;
    END IF;

    -- Find the requested food item
    SELECT
        item_id,
        price
    INTO
        v_item_id,
        v_price
    FROM food_items
    WHERE LOWER(name) = LOWER(TRIM(p_food_item));

    -- Reject food items that are not on the menu
    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Food item "%" does not exist on the menu.',
            p_food_item;
    END IF;

    -- Insert the new item.
    -- If it already exists, increase its quantity and price.
    INSERT INTO orders (
        order_id,
        item_id,
        quantity,
        total_price
    )
    VALUES (
        p_order_id,
        v_item_id,
        p_quantity,
        v_price * p_quantity
    )
    ON CONFLICT (order_id, item_id)
    DO UPDATE SET
        quantity =
            orders.quantity + EXCLUDED.quantity,

        total_price =
            (orders.quantity + EXCLUDED.quantity) * v_price;
END;
$$;


-- ============================================================
-- Optional helper function: create a new order ID
--
-- Returns the next available order ID.
-- This keeps the tutorial's database structure while avoiding
-- hard-coded IDs in the Python backend.
-- ============================================================

CREATE OR REPLACE FUNCTION get_next_order_id()
RETURNS INTEGER
LANGUAGE sql
VOLATILE
AS $$
    SELECT COALESCE(MAX(order_id), 0) + 1
    FROM (
        SELECT order_id FROM orders

        UNION

        SELECT order_id FROM order_tracking
    ) AS existing_orders;
$$;


-- ============================================================
-- Optional procedure: finalize an order
--
-- Adds the completed order to the tracking table.
-- ============================================================

CREATE OR REPLACE PROCEDURE finalize_order(
    p_order_id INTEGER
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM orders
        WHERE order_id = p_order_id
    ) THEN
        RAISE EXCEPTION
            'Order % does not contain any items.',
            p_order_id;
    END IF;

    INSERT INTO order_tracking (
        order_id,
        status
    )
    VALUES (
        p_order_id,
        'confirmed'
    )
    ON CONFLICT (order_id)
    DO UPDATE SET
        status = EXCLUDED.status;
END;
$$;


